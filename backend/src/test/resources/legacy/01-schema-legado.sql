SET NAMES utf8mb4;
-- Esquema do banco LEGADO (petshop_db) para testes e para o perfil Docker "migracao".
-- Mesmas tabelas e colunas do script do PHP (docs/legacy/...), sem procedures e sem FKs,
-- e com VARCHAR no lugar de ENUM: assim a fixture consegue simular dado sujo (valores
-- fora do enum, órfãos) que existe em bancos reais antigos. Nenhum dado aqui.

CREATE TABLE papel (id INT AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(50) NOT NULL, descricao TEXT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE usuario (id INT AUTO_INCREMENT PRIMARY KEY, usuario VARCHAR(50) NOT NULL, senha_hash VARCHAR(255) NOT NULL,
    token_senha VARCHAR(255) NULL, token_expira DATETIME NULL, email VARCHAR(100) NOT NULL, papel_id INT NOT NULL,
    ativo TINYINT(1) DEFAULT 1, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP);
CREATE TABLE super_usuario (id INT AUTO_INCREMENT PRIMARY KEY, usuario_id INT NOT NULL, cargo VARCHAR(50) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE funcionario (id INT AUTO_INCREMENT PRIMARY KEY, usuario_id INT NOT NULL, nome VARCHAR(100) NOT NULL,
    cpf VARCHAR(14) NOT NULL, data_nascimento DATE NULL, sexo VARCHAR(20) NOT NULL DEFAULT 'Outro', telefone VARCHAR(15) NULL,
    cep VARCHAR(10) NULL, rua VARCHAR(150) NULL, bairro VARCHAR(100) NULL, numero VARCHAR(20) NULL,
    complemento VARCHAR(100) NULL, observacoes TEXT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP);
CREATE TABLE cliente (id INT AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(100) NOT NULL, cpf VARCHAR(14) NULL,
    data_nascimento DATE NULL, telefone VARCHAR(15) NOT NULL, email VARCHAR(100) NULL, cep VARCHAR(10) NULL,
    rua VARCHAR(150) NULL, bairro VARCHAR(100) NULL, numero VARCHAR(20) NULL, complemento VARCHAR(100) NULL,
    observacoes TEXT NULL, ativo TINYINT(1) DEFAULT 1, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP, estado VARCHAR(20) NULL);
CREATE TABLE fornecedor (id INT AUTO_INCREMENT PRIMARY KEY, nome_fantasia VARCHAR(100) NOT NULL, razao_social VARCHAR(150) NULL,
    cnpj VARCHAR(18) NOT NULL, telefone VARCHAR(15) NULL, email VARCHAR(100) NULL, contato VARCHAR(100) NULL,
    cep VARCHAR(10) NULL, rua VARCHAR(150) NULL, bairro VARCHAR(100) NULL, numero VARCHAR(20) NULL,
    complemento VARCHAR(100) NULL, observacoes TEXT NULL, ativo TINYINT(1) DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP);
CREATE TABLE especie (id INT AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE raca (id INT AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(50) NOT NULL, especie_id INT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE pet (id INT AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(50) NOT NULL, cliente_id INT NOT NULL, especie_id INT NOT NULL,
    raca_id INT NULL, data_nascimento DATE NULL, peso DECIMAL(5,2) NULL, cor VARCHAR(30) NULL, castrado TINYINT(1) DEFAULT 0,
    vacinado TINYINT(1) DEFAULT 0, observacoes TEXT NULL, foto VARCHAR(255) NULL, ativo TINYINT(1) DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP, porte VARCHAR(20) NULL);
CREATE TABLE vacina (id INT AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(100) NOT NULL, doenca_protecao VARCHAR(150) NULL,
    validade_padrao_meses INT DEFAULT 12, preco DECIMAL(10,2) NULL, observacoes TEXT NULL, ativo TINYINT(1) DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP, especie_id INT NOT NULL);
CREATE TABLE carteira_vacina (id INT AUTO_INCREMENT PRIMARY KEY, pet_id INT NOT NULL, nome_vacina VARCHAR(100) NOT NULL,
    data_aplicacao DATE NOT NULL, data_proxima DATE NULL, veterinario VARCHAR(100) NULL, observacoes TEXT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE historico_consulta (id INT AUTO_INCREMENT PRIMARY KEY, pet_id INT NOT NULL, data_consulta DATETIME NOT NULL,
    veterinario VARCHAR(100) NOT NULL, motivo TEXT NULL, diagnostico TEXT NULL, tratamento TEXT NULL, observacoes TEXT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE servico (id INT AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(100) NOT NULL, descricao TEXT NULL,
    preco DECIMAL(10,2) NOT NULL, duracao_media INT NULL, ativo TINYINT(1) DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP);
CREATE TABLE preco_servico_porte (id INT AUTO_INCREMENT PRIMARY KEY, servico_id INT NOT NULL, porte VARCHAR(20) NOT NULL,
    preco DECIMAL(10,2) NOT NULL);
CREATE TABLE agendamento (id INT AUTO_INCREMENT PRIMARY KEY, pet_id INT NOT NULL, servico_id INT NOT NULL,
    funcionario_id INT NULL, data_agendamento DATETIME NOT NULL, status VARCHAR(30) DEFAULT 'agendado', observacoes TEXT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    total_estimado DECIMAL(10,2) NOT NULL DEFAULT 0.00);
CREATE TABLE servico_realizado (id INT AUTO_INCREMENT PRIMARY KEY, agendamento_id INT NULL, pet_id INT NOT NULL,
    servico_id INT NOT NULL, funcionario_id INT NULL, data_servico DATETIME DEFAULT CURRENT_TIMESTAMP,
    valor DECIMAL(10,2) NOT NULL, observacoes TEXT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE categoria_produto (id INT AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(50) NOT NULL, descricao TEXT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE produto (id INT AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(100) NOT NULL, descricao TEXT NULL,
    categoria_id INT NOT NULL, fornecedor_padrao_id INT NULL, preco_custo DECIMAL(10,2) NULL, preco_venda DECIMAL(10,2) NOT NULL,
    quantidade_estoque INT DEFAULT 0, estoque_minimo INT DEFAULT 5, codigo_barras VARCHAR(50) NULL, ativo TINYINT(1) DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP);
CREATE TABLE compra (id INT AUTO_INCREMENT PRIMARY KEY, fornecedor_id INT NOT NULL, funcionario_id INT NULL,
    data_compra DATE NOT NULL, data_entrega DATE NULL, valor_total DECIMAL(10,2) NOT NULL, status VARCHAR(20) DEFAULT 'pedido',
    forma_pagamento VARCHAR(50) NULL, observacoes TEXT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE item_compra (id INT AUTO_INCREMENT PRIMARY KEY, compra_id INT NOT NULL, produto_id INT NOT NULL,
    quantidade INT NOT NULL, preco_custo_unitario DECIMAL(10,2) NOT NULL, subtotal DECIMAL(10,2) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE venda (id INT AUTO_INCREMENT PRIMARY KEY, cliente_id INT NULL, funcionario_id INT NULL,
    data_venda DATETIME DEFAULT CURRENT_TIMESTAMP, valor_total DECIMAL(10,2) NOT NULL, desconto DECIMAL(10,2) DEFAULT 0.00,
    forma_pagamento VARCHAR(30) NULL, observacoes TEXT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE item_venda (id INT AUTO_INCREMENT PRIMARY KEY, venda_id INT NOT NULL, produto_id INT NOT NULL,
    quantidade INT NOT NULL, preco_unitario DECIMAL(10,2) NOT NULL, subtotal DECIMAL(10,2) NOT NULL);
CREATE TABLE movimentacao_financeira (id INT AUTO_INCREMENT PRIMARY KEY, tipo VARCHAR(20) NOT NULL, descricao VARCHAR(100) NOT NULL,
    valor DECIMAL(10,2) NOT NULL, data_movimentacao DATE NOT NULL, categoria VARCHAR(40) NULL, referencia_id INT NULL,
    observacoes TEXT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
